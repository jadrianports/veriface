#!/usr/bin/env python3
"""Generate and check ``docs/adr/README.md``, the ADR index.

Usage::

    tools/adr_index.py --write   # regenerate docs/adr/README.md
    tools/adr_index.py --check   # exit non-zero if the committed index is stale

The index lists every ``docs/adr/NNNN-*.md`` record in ascending numeric order
by its four-digit filename prefix. Duplicate prefixes are rejected rather than
silently deduplicated or sorted around — a duplicate number is a data error,
not a rendering choice.

Deterministic on purpose: LF line endings regardless of host OS, no
timestamp, no locale-dependent sort (plain string comparison on a fixed-width
zero-padded prefix). Running ``--write`` twice in a row must produce a
byte-identical file.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ADR_DIR = REPO_ROOT / "docs" / "adr"
INDEX_PATH = ADR_DIR / "README.md"

FILENAME_RE = re.compile(r"^(?P<number>\d{4})-[a-z0-9-]+\.md$")
TITLE_RE = re.compile(r"^#\s+(?P<title>.+?)\s*$", re.MULTILINE)
STATUS_RE = re.compile(r"^## Status\s*\n+\s*(?P<status>\S+)", re.MULTILINE)

Record = tuple[str, str, str, Path]


class AdrIndexError(RuntimeError):
    """Raised when the ADR set cannot be indexed, e.g. a duplicate number."""


def discover_records() -> list[Record]:
    """Return ``(number, title, status, path)`` tuples, sorted ascending.

    Raises ``AdrIndexError`` if two files share the same four-digit prefix.
    """
    records: list[Record] = []
    seen: dict[str, Path] = {}
    for path in sorted(ADR_DIR.glob("[0-9][0-9][0-9][0-9]-*.md")):
        match = FILENAME_RE.match(path.name)
        if match is None:
            continue
        number = match.group("number")
        if number in seen:
            raise AdrIndexError(
                f"duplicate ADR number {number}: {seen[number].name} and {path.name} both claim it"
            )
        seen[number] = path
        text = path.read_text(encoding="utf-8")
        title_match = TITLE_RE.search(text)
        status_match = STATUS_RE.search(text)
        title = title_match.group("title") if title_match else path.stem
        status = status_match.group("status") if status_match else "unknown"
        records.append((number, title, status, path))
    records.sort(key=lambda record: record[0])
    return records


def render_index(records: list[Record]) -> str:
    lines = [
        "# Architecture Decision Records",
        "",
        "An ADR captures one significant, load-bearing architectural decision: the "
        "context that forced it, the options actually weighed, and the outcome. "
        "Records are numbered and never edited after acceptance — a changed decision "
        "is a new record that supersedes the old one, and the superseded record keeps "
        "its original text.",
        "",
        "Generated by `tools/adr_index.py --write`. Do not hand-edit the table below.",
        "",
        "| Number | Title | Status |",
        "| --- | --- | --- |",
    ]
    for number, title, status, path in records:
        lines.append(f"| [{number}]({path.name}) | {title} | {status} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate docs/adr/README.md")
    group.add_argument("--check", action="store_true", help="exit non-zero if the index is stale")
    args = parser.parse_args(argv)

    try:
        records = discover_records()
    except AdrIndexError as exc:
        print(f"adr_index: {exc}", file=sys.stderr)
        return 1

    rendered = render_index(records)

    if args.write:
        INDEX_PATH.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"adr_index: wrote {INDEX_PATH} ({len(records)} records)")
        return 0

    if not INDEX_PATH.exists():
        print(f"adr_index: {INDEX_PATH} does not exist; run --write first", file=sys.stderr)
        return 1
    current = INDEX_PATH.read_text(encoding="utf-8")
    if current != rendered:
        print(
            "adr_index: docs/adr/README.md is stale; run tools/adr_index.py --write",
            file=sys.stderr,
        )
        return 1
    print(f"adr_index: {INDEX_PATH} is up to date ({len(records)} records)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
