"""The CelebA-Spoof subset manifest: schema, seeded sampler, and its invariants (D-19/D-21).

A **committed manifest** — subject ids, relative paths, attack-class labels —
is reproducible unconditionally because it is built from a *sorted* view of
the label index before any random sampling touches it (D-19's whole reason
for existing: a bare seed is only reproducible if the enumeration order that
feeds it is stable, and that stability cannot be guaranteed for a downloaded
corpus). Every property below is an assertion, not a comment:

- **Sort first.** Distinct subject ids are sorted into one canonical order
  before anything seeded touches them, so the selected subject *set* depends
  only on the seed and the pool's content, never on the order the caller's
  label index happened to enumerate them in.
- **Subject-first, then attack-balanced (D-21).** Whole subjects are drawn
  from a single seeded permutation of the full pool; ``tier`` config slices
  contiguous, non-overlapping ranges out of that one permutation via
  ``subject_pool_offset``, which is what makes the eval and extended tiers
  structurally disjoint for the same seed rather than merely usually
  disjoint. Only once subjects are fixed does per-class balancing subsample
  images within them.
- **Ties broken by subject id, specified rather than incidental.** The
  pool permutation is a sort of ``(draw, subject_id)`` pairs — a real float
  collision in ``draw`` essentially never happens, but the tie-break is part
  of the sort key, not an accident of ``sorted()``. Manifest row order is
  likewise a specified ``(subject_id, relative_path)`` sort, not whatever
  order dict iteration or set membership happened to produce.
"""

from __future__ import annotations

import csv
import hashlib
import json
import random
from collections.abc import Iterable, Mapping, Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict

from veriface.errors import VerifaceError
from veriface.hashing import sha256_file

SAMPLER_VERSION = "1"

SpoofClass = Literal["live", "print", "screen_replay"]
"""D-39: video-replay is out of v1 — this Literal is the structural guard;
a ``ManifestRow`` cannot be constructed with any other value."""


class ManifestValidationError(VerifaceError):
    """Base class for every error this module raises deliberately."""


class EmptyLabelIndexError(ManifestValidationError):
    """Raised when ``build_manifest`` is given a label index with no rows."""

    def __init__(self) -> None:
        super().__init__(
            "build_manifest received an empty label index — there is nothing to sample from."
        )


class InsufficientSubjectPoolError(ManifestValidationError):
    """Raised when a tier's requested subject slice exceeds the available pool."""

    def __init__(self, requested_end: int, pool_size: int) -> None:
        self.requested_end = requested_end
        self.pool_size = pool_size
        super().__init__(
            f"Tier requests subjects up to index {requested_end} "
            f"(subject_pool_offset + target_subjects) but the label index only has "
            f"{pool_size} distinct subjects — never silently under-fills, raise instead."
        )


class InvalidSamplerParamsError(ManifestValidationError):
    """Raised when ``params`` is missing a required key or fails validation."""


class UnsupportedSamplerVersionError(ManifestValidationError):
    """Raised by ``read_manifest`` when a manifest's ``sampler_version`` is not this module's."""

    def __init__(self, found: str) -> None:
        self.found = found
        super().__init__(
            f"Manifest was generated by sampler_version {found!r}; this module only "
            f"understands {SAMPLER_VERSION!r}. Regenerate the manifest with the current sampler."
        )


class ManifestRow(BaseModel):
    """One selected image: which subject, where, and under which attack class."""

    model_config = ConfigDict(frozen=True)

    subject_id: str
    relative_path: str
    spoof_class: SpoofClass
    split: str


class ManifestHeader(BaseModel):
    """Self-describing generation record — enough to tell whether a manifest and
    a label index belong together (D-19)."""

    model_config = ConfigDict(frozen=True)

    seed: int
    tier: str
    sampler_version: str
    params: dict[str, Any]
    label_index_sha256: str
    generated_at: str
    description: str


LabelIndexEntry = tuple[str, str, str]
"""``(subject_id, relative_path, spoof_class)`` — the shape ``build_label_index``
(plan 01-07) produces and this module consumes."""


def _hash_label_index(label_index: Iterable[LabelIndexEntry]) -> str:
    """A deterministic, order-independent digest of a label index's content.

    Not ``sha256_file`` — there is no single file backing the label index at
    this stage (it may be assembled in memory from a freshly extracted
    archive). Sorted first for the same order-independence reason every
    other step in this module sorts first.
    """
    digest = hashlib.sha256()
    for subject_id, relative_path, spoof_class in sorted(label_index):
        digest.update(f"{subject_id}\t{relative_path}\t{spoof_class}\n".encode())
    return digest.hexdigest()


def _validate_params(params: Mapping[str, Any]) -> tuple[int, int, float, dict[str, float]]:
    try:
        target_subjects = int(params["target_subjects"])
        splits = dict(params["splits"])
    except KeyError as exc:
        raise InvalidSamplerParamsError(f"params is missing required key {exc}") from exc

    subject_pool_offset = int(params.get("subject_pool_offset", 0))
    class_balance_tolerance = float(params.get("class_balance_tolerance", 0.0))

    if target_subjects <= 0:
        raise InvalidSamplerParamsError("params['target_subjects'] must be positive")
    if subject_pool_offset < 0:
        raise InvalidSamplerParamsError("params['subject_pool_offset'] must be non-negative")
    if not splits:
        raise InvalidSamplerParamsError("params['splits'] must declare at least one split")
    total = sum(splits.values())
    if abs(total - 1.0) > 1e-6:
        raise InvalidSamplerParamsError(
            f"params['splits'] proportions must sum to 1.0, got {total}"
        )

    return target_subjects, subject_pool_offset, class_balance_tolerance, splits


def _deterministic_pool_permutation(subject_ids_sorted: Sequence[str], seed: int) -> list[str]:
    """One seeded permutation of the *entire* subject pool, independent of ``tier``.

    Depends only on the sorted subject-id sequence and the seed — never on
    the label index's own enumeration order (that dependency was already
    removed by sorting before this function is called) and never on which
    tier is asking. This is what makes contiguous slices of the same
    permutation (one per tier, via ``subject_pool_offset``) structurally
    disjoint rather than independently-and-coincidentally disjoint.
    """
    rng = random.Random(f"{seed}:pool")
    scored = sorted((rng.random(), subject_id) for subject_id in subject_ids_sorted)
    return [subject_id for _draw, subject_id in scored]


def _assign_splits(
    selected_subject_ids: Sequence[str], *, seed: int, tier: str, splits: Mapping[str, float]
) -> dict[str, str]:
    """Partition ``selected_subject_ids`` into named, non-overlapping splits.

    A subject belongs to exactly one split (D-21's "no subject spans two
    evaluation splits"), assigned by slicing a seeded permutation of the
    selected subjects — largest-remainder rounding decides each split's
    exact count so the total always equals the input size exactly.
    """
    rng = random.Random(f"{seed}:{tier}:splits")
    scored = sorted((rng.random(), subject_id) for subject_id in selected_subject_ids)
    ordered = [subject_id for _draw, subject_id in scored]

    n = len(ordered)
    split_names = sorted(splits)  # deterministic iteration order, independent of dict insertion
    raw_counts = {name: splits[name] * n for name in split_names}
    counts = {name: int(raw_counts[name]) for name in split_names}
    remainder = n - sum(counts.values())
    # Largest-remainder method: give the leftover units to the splits with the
    # largest fractional part, ties broken by split name for determinism.
    fractional_order = sorted(
        split_names, key=lambda name: (-(raw_counts[name] - counts[name]), name)
    )
    for name in fractional_order[:remainder]:
        counts[name] += 1

    assignment: dict[str, str] = {}
    cursor = 0
    for name in split_names:
        for subject_id in ordered[cursor : cursor + counts[name]]:
            assignment[subject_id] = name
        cursor += counts[name]
    return assignment


def _balance_classes(
    rows_by_class: Mapping[str, list[LabelIndexEntry]], *, seed: int, tier: str
) -> list[LabelIndexEntry]:
    """Downsample every class to the smallest class's count (deterministic, exact balance).

    Exact equality always satisfies any non-negative ``class_balance_tolerance``
    — this is a legitimate, simple balancing strategy (cap to the minority
    class), not a shortcut around the invariant.
    """
    if not rows_by_class:
        return []
    target_count = min(len(rows) for rows in rows_by_class.values())
    balanced: list[LabelIndexEntry] = []
    for spoof_class in sorted(rows_by_class):
        candidates = sorted(rows_by_class[spoof_class])
        if len(candidates) <= target_count:
            balanced.extend(candidates)
            continue
        rng = random.Random(f"{seed}:{tier}:balance:{spoof_class}")
        balanced.extend(rng.sample(candidates, k=target_count))
    return balanced


def build_manifest(
    label_index: Sequence[LabelIndexEntry],
    *,
    tier: str,
    seed: int,
    params: Mapping[str, Any],
) -> tuple[ManifestHeader, list[ManifestRow]]:
    """Build a reproducible, subject-disjoint, attack-balanced manifest.

    ``params`` required keys: ``target_subjects`` (int), ``splits``
    (``dict[str, float]`` summing to ``1.0``). Optional: ``subject_pool_offset``
    (int, default ``0`` — the tier's slice start into the shared pool
    permutation) and ``class_balance_tolerance`` (float, default ``0.0``).

    Calling this twice with identical arguments returns identical rows in
    identical order (D-19); the header's ``generated_at`` is the only field
    that legitimately differs between calls.
    """
    if not label_index:
        raise EmptyLabelIndexError()

    target_subjects, subject_pool_offset, class_balance_tolerance, splits = _validate_params(params)

    by_subject: dict[str, list[LabelIndexEntry]] = {}
    for entry in label_index:
        by_subject.setdefault(entry[0], []).append(entry)
    subject_ids_sorted = sorted(by_subject)  # canonical total order (D-19's "sort first")

    pool_permutation = _deterministic_pool_permutation(subject_ids_sorted, seed)
    slice_end = subject_pool_offset + target_subjects
    if slice_end > len(pool_permutation):
        raise InsufficientSubjectPoolError(slice_end, len(pool_permutation))
    selected_subject_ids = sorted(pool_permutation[subject_pool_offset:slice_end])

    subject_to_split = _assign_splits(selected_subject_ids, seed=seed, tier=tier, splits=splits)

    rows_by_class: dict[str, list[LabelIndexEntry]] = {}
    for subject_id in selected_subject_ids:
        for entry in by_subject[subject_id]:
            rows_by_class.setdefault(entry[2], []).append(entry)

    balanced_entries = _balance_classes(rows_by_class, seed=seed, tier=tier)

    rows = [
        ManifestRow(
            subject_id=subject_id,
            relative_path=relative_path,
            spoof_class=spoof_class,  # type: ignore[arg-type]
            split=subject_to_split[subject_id],
        )
        for subject_id, relative_path, spoof_class in balanced_entries
    ]
    rows.sort(key=lambda row: (row.subject_id, row.relative_path))

    header = ManifestHeader(
        seed=seed,
        tier=tier,
        sampler_version=SAMPLER_VERSION,
        params=dict(params),
        label_index_sha256=_hash_label_index(label_index),
        generated_at=datetime.now(UTC).isoformat(),
        description=(
            f"CelebA-Spoof {tier!r} tier subset — {len(selected_subject_ids)} subjects, "
            f"seed {seed}, sampler v{SAMPLER_VERSION}."
        ),
    )
    return header, rows


_HEADER_FIELD_ORDER = (
    "seed",
    "tier",
    "sampler_version",
    "params",
    "label_index_sha256",
    "generated_at",
    "description",
)
_CSV_COLUMNS = ("subject_id", "relative_path", "spoof_class", "split")


def write_manifest(rows: Sequence[ManifestRow], header: ManifestHeader, path: Path) -> None:
    """Write ``header`` as leading ``#``-comment lines, then a CSV body.

    LF line endings only, on every platform (``newline=""`` plus an explicit
    ``lineterminator``) — a manifest diffed in review must never show a
    whole-file CRLF/LF churn from the OS that happened to regenerate it.
    Rows are written in ``rows``' own order; ``build_manifest`` already
    guarantees that order is ``(subject_id, relative_path)``.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    header_dict = header.model_dump()
    with path.open("w", newline="", encoding="utf-8") as fh:
        for field in _HEADER_FIELD_ORDER:
            value = header_dict[field]
            serialized = json.dumps(value) if field == "params" else str(value)
            fh.write(f"# {field}: {serialized}\n")
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerow(_CSV_COLUMNS)
        for row in rows:
            writer.writerow([row.subject_id, row.relative_path, row.spoof_class, row.split])


def read_manifest(path: Path) -> tuple[ManifestHeader, list[ManifestRow]]:
    """Parse a manifest written by ``write_manifest`` back into ``(header, rows)``.

    Raises ``UnsupportedSamplerVersionError`` if the header's
    ``sampler_version`` is not this module's ``SAMPLER_VERSION``.
    """
    with path.open("r", newline="", encoding="utf-8") as fh:
        raw_header: dict[str, str] = {}
        line = fh.readline()
        while line.startswith("#"):
            field, _, value = line[1:].strip().partition(": ")
            raw_header[field] = value
            line = fh.readline()

        # `line` now holds the CSV column-header row already consumed from
        # the same file handle; hand the remainder to csv.reader as-is.
        reader = csv.reader([line, *fh.read().splitlines()])
        column_header = next(reader)
        if tuple(column_header) != _CSV_COLUMNS:
            raise ManifestValidationError(
                f"Unexpected manifest column header {column_header!r}, expected {_CSV_COLUMNS!r}"
            )
        rows = [
            ManifestRow(
                subject_id=record[0],
                relative_path=record[1],
                spoof_class=record[2],  # type: ignore[arg-type]
                split=record[3],
            )
            for record in reader
            if record
        ]

    sampler_version = raw_header["sampler_version"]
    if sampler_version != SAMPLER_VERSION:
        raise UnsupportedSamplerVersionError(sampler_version)

    header = ManifestHeader(
        seed=int(raw_header["seed"]),
        tier=raw_header["tier"],
        sampler_version=sampler_version,
        params=json.loads(raw_header["params"]),
        label_index_sha256=raw_header["label_index_sha256"],
        generated_at=raw_header["generated_at"],
        description=raw_header["description"],
    )
    return header, rows


def manifest_sha256(path: Path) -> str:
    """Digest of a committed manifest file — delegates to the core hashing helper."""
    return sha256_file(path)


