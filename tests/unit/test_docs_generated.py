"""D-37, structural: README's licence matrix and NOTICE cannot drift (T-01-13).

Both documents are generated by ``veriface docs licenses`` and never hand-edited. This module
re-runs the same in-process renderers (``render_license_matrix`` / ``render_notice``) and diffs
their output against what is committed — a single character of hand-editing inside the marked
README block or NOTICE makes this suite fail, which is the whole point (see the plan's acceptance
criterion: "editing one character inside the README matrix block makes it fail").
"""

from __future__ import annotations

import re
from pathlib import Path
from urllib.parse import urlparse

from veriface.licensing import render_license_matrix, render_notice
from veriface.models.specs import PROFILES

REPO_ROOT = Path(__file__).resolve().parents[2]
README_PATH = REPO_ROOT / "README.md"
NOTICE_PATH = REPO_ROOT / "NOTICE"

BEGIN_MARKER = "<!-- BEGIN licence-matrix -->\n"
END_MARKER = "<!-- END licence-matrix -->"

D05_WARNING_LINE = "> ⚠️ Non-commercial research use only — see Licensing."

_ALLOWED_BADGE_HOSTS = frozenset({"github.com", "img.shields.io", "shields.io"})

# Matches the image half of a Markdown badge: ![alt](https://host/...)
_MARKDOWN_IMAGE_URL_RE = re.compile(r"!\[[^\]]*\]\((https?://[^)\s]+)\)")


def _readme_text() -> str:
    return README_PATH.read_text(encoding="utf-8")


def _distinct_spec_names() -> set[str]:
    return {spec.name for specs in PROFILES.values() for spec in specs}


def _embedded_matrix(readme_text: str) -> str:
    start = readme_text.index(BEGIN_MARKER) + len(BEGIN_MARKER)
    stop = readme_text.index(END_MARKER)
    return readme_text[start:stop]


def test_readme_licence_matrix_matches_freshly_rendered_matrix() -> None:
    readme_text = _readme_text()
    embedded = _embedded_matrix(readme_text)
    assert embedded == render_license_matrix(), (
        "README's licence-matrix block has drifted from `veriface docs licenses --format matrix` "
        "output — regenerate it with `uv run veriface docs licenses --format matrix` and paste "
        "the result between the BEGIN/END markers; never hand-edit the table."
    )


def test_notice_file_matches_freshly_rendered_notice() -> None:
    notice_text = NOTICE_PATH.read_text(encoding="utf-8")
    assert notice_text == render_notice(), (
        "NOTICE has drifted from `veriface docs licenses --format notice` output — regenerate it "
        "with `uv run veriface docs licenses --format notice --out NOTICE`; never hand-edit it."
    )


def test_readme_contains_d05_warning_line() -> None:
    assert D05_WARNING_LINE in _readme_text()


def test_readme_first_heading_is_project_title() -> None:
    first_line = _readme_text().splitlines()[0]
    assert first_line == "# veriface"


def test_readme_contains_every_default_profile_artifact_name() -> None:
    readme_text = _readme_text()
    for name in _distinct_spec_names():
        assert name in readme_text, f"README is missing artifact name {name!r}"


def test_readme_badge_image_hosts_are_github_or_shields_only() -> None:
    readme_text = _readme_text()
    image_urls = _MARKDOWN_IMAGE_URL_RE.findall(readme_text)
    assert image_urls, "no badge image URLs found in README — expected at least one badge row"
    offending = [url for url in image_urls if urlparse(url).netloc not in _ALLOWED_BADGE_HOSTS]
    assert offending == [], f"badge image URL(s) hosted outside github.com/shields.io: {offending}"


def test_readme_artifact_recovery_section_names_no_private_archive_location() -> None:
    """D-08: the recovery procedure is documented; the private archive's location is not.

    No filesystem path outside the repo, no non-github/huggingface hostname, and no account name
    for the private local+offsite archive may appear anywhere in README.
    """
    readme_text = _readme_text().lower()
    forbidden_markers = (
        "c:\\users",
        "/home/",
        "~/",
        "backblaze",
        "s3://",
        "dropbox",
        "google drive",
        "onedrive",
    )
    offending = [marker for marker in forbidden_markers if marker in readme_text]
    assert offending == [], f"README appears to name a private archive detail: {offending}"


def test_editing_matrix_block_content_would_fail_the_drift_check() -> None:
    """Demonstrates the drift check actually detects a one-character edit (acceptance criterion).

    Does not mutate the committed README — mutates an in-memory copy and re-runs the same
    comparison the other tests perform against the real file.
    """
    readme_text = _readme_text()
    embedded = _embedded_matrix(readme_text)
    tampered = embedded[:-2] + "X" + embedded[-1] if len(embedded) >= 2 else embedded + "X"
    assert tampered != render_license_matrix(), (
        "tampering with the embedded matrix text should make it differ from the freshly "
        "rendered matrix, but it did not — the drift check would not catch a real edit"
    )
